MoleculeContactDescriptor = tuple[str, str, PeriodicSymmetryRelation]


def molecular_component_stabilizer(
    component: MolecularComponentOrbit,
    context: SymmetryContext,
) -> tuple[PeriodicSymmetryRelation, ...]:
    """Expand the finite exact stabilizer generated by a discrete component."""

    if component.kind is not MolecularComponentKind.DISCRETE_MOLECULE:
        raise ValueError("molecule stabilizers require a discrete molecular component")
    identity = identity_relation(context)
    generators = tuple(sorted(set(
        (
            *component.closure_relations,
            *(relation.inverse(context) for relation in component.closure_relations),
        )
    )))
    subgroup = {identity}
    queue = deque((identity,))
    maximum_finite_order = len(context.operations)
    while queue:
        current = queue.popleft()
        for generator in generators:
            candidate = current.compose(generator, context)
            if candidate in subgroup:
                continue
            subgroup.add(candidate)
            if len(subgroup) > maximum_finite_order:
                raise ValueError("discrete molecule stabilizer generated an infinite relation set")
            queue.append(candidate)
    return tuple(sorted(subgroup))


def molecule_relation_for_atomic_pair(
    first_component: MolecularComponentOrbit,
    second_component: MolecularComponentOrbit,
    first_site_id: str,
    second_site_id: str,
    atomic_relation: PeriodicSymmetryRelation,
    context: SymmetryContext,
) -> PeriodicSymmetryRelation:
    """Express an atomic pair relation in the two molecule reference frames."""

    first_images = dict(first_component.image_relations)
    second_images = dict(second_component.image_relations)
    if first_site_id not in first_images or second_site_id not in second_images:
        raise ValueError("atomic pair endpoint is outside its molecular component")
    return (
        first_images[first_site_id]
        .compose(atomic_relation, context)
        .compose(second_images[second_site_id].inverse(context), context)
    )


def canonical_molecule_contact_relation(
    first_component: MolecularComponentOrbit,
    second_component: MolecularComponentOrbit,
    relation: PeriodicSymmetryRelation,
    context: SymmetryContext,
) -> MoleculeContactDescriptor:
    """Canonicalize an undirected molecule relation by both stabilizers."""

    return canonical_undirected_relation(
        first_component.component_orbit_id,
        second_component.component_orbit_id,
        relation,
        molecular_component_stabilizer(first_component, context),
        molecular_component_stabilizer(second_component, context),
        context,
    )


def _vdw_evidence(
    first_site,
    second_site,
    distance: float,
    reference: ReferenceData,
) -> tuple[tuple[VanDerWaalsDistanceEvidence, ...], tuple[Diagnostic, ...]]:
    evidence: list[VanDerWaalsDistanceEvidence] = []
    diagnostics: list[Diagnostic] = []
    for first_component in first_site.components:
        for second_component in second_site.components:
            if first_component.element is None or second_component.element is None:
                diagnostics.append(Diagnostic(
                    Severity.WARNING,
                    "crystal_chemistry.intermolecular.unknown_component_element",
                    "An intermolecular component has no resolvable parent element",
                ))
                continue
            first_element = first_component.element
            second_element = second_component.element
            first_occupancy = float(first_component.occupancy.value)
            second_occupancy = float(second_component.occupancy.value)
            try:
                first_radius = reference.vdw_radii.find(first_element).value_angstrom
                second_radius = reference.vdw_radii.find(second_element).value_angstrom
            except KeyError:
                evidence.append(VanDerWaalsDistanceEvidence(
                    first_element,
                    second_element,
                    first_occupancy,
                    second_occupancy,
                    None,
                    None,
                    None,
                    ResolutionStatus.INCOMPLETE,
                ))
                diagnostics.append(Diagnostic(
                    Severity.WARNING,
                    "crystal_chemistry.intermolecular.vdw_radius_missing",
                    f"No van der Waals radius is available for {first_element}-{second_element}",
                ))
                continue
            radius_sum = first_radius + second_radius
            evidence.append(VanDerWaalsDistanceEvidence(
                first_element,
                second_element,
                first_occupancy,
                second_occupancy,
                radius_sum,
                distance - radius_sum,
                distance / radius_sum,
                ResolutionStatus.RESOLVED,
            ))
    evidence.sort(key=lambda item: (
        item.first_element,
        item.second_element,
        item.first_occupancy,
        item.second_occupancy,
    ))
    return tuple(evidence), tuple(dict.fromkeys(diagnostics))


def _same_molecule_instance(
    first: MolecularComponentOrbit,
    second: MolecularComponentOrbit,
    relation: PeriodicSymmetryRelation,
    context: SymmetryContext,
) -> bool:
    if first.component_orbit_id != second.component_orbit_id:
        return False
    actual = canonical_molecule_contact_relation(first, second, relation, context)
    identity = canonical_molecule_contact_relation(
        first,
        second,
        identity_relation(context),
        context,
    )
    return actual == identity


def _relation_vector(
    first_site,
    second_site,
    relation: PeriodicSymmetryRelation,
    contact_analysis: ContactAnalysisResult,
) -> tuple[float, tuple[float, float, float]]:
    context = contact_analysis._symmetry_context
    operation = context.operation_by_key(relation.operation_key)
    first = np.asarray(tuple(float(item.value) for item in first_site.fractional))
    second = tuple(float(item.value) for item in second_site.fractional)
    transformed = np.asarray(tuple(
        math.fsum(
            float(coefficient) * coordinate
            for coefficient, coordinate in zip(row, second, strict=True)
        )
        + float(offset)
        + relation.lattice_translation[index]
        for index, (row, offset) in enumerate(
            zip(operation.rotation, operation.translation, strict=True)
        )
    ))
    vector = (transformed - first) @ contact_analysis._structure.cell.matrix
    return float(np.linalg.norm(vector)), tuple(float(value) for value in vector)


def _hydrogen_bond_candidates(
    orbit: IntermolecularContactOrbit,
    geometry,
    contact_analysis: ContactAnalysisResult,
    molecular_analysis: MolecularAnalysisResult,
    policy: IntermolecularContactPolicy,
) -> tuple[HydrogenBondCandidate, ...]:
    sites = {site.id: site for site in contact_analysis._structure.sites}
    first_site = sites[geometry.first_independent_site_id]
    second_site = sites[geometry.second_independent_site_id]
    first_has_h = any(component.element == "H" for component in first_site.components)
    second_has_h = any(component.element == "H" for component in second_site.components)
    if first_has_h == second_has_h:
        return ()
    if first_has_h:
        hydrogen_id = geometry.first_independent_site_id
        acceptor_id = geometry.second_independent_site_id
        hydrogen_acceptor_relation = geometry.canonical_relation
        qualifying_evidence = tuple(
            item
            for item in orbit.component_pair_evidence
            if item.first_element == "H"
            and item.second_element in policy.hydrogen_acceptor_elements
            and item.vdw_gap is not None
            and item.vdw_gap <= policy.hydrogen_acceptor_gap_angstrom
        )
    else:
        hydrogen_id = geometry.second_independent_site_id
        acceptor_id = geometry.first_independent_site_id
        hydrogen_acceptor_relation = geometry.canonical_relation.inverse(
            contact_analysis._symmetry_context
        )
        qualifying_evidence = tuple(
            item
            for item in orbit.component_pair_evidence
            if item.second_element == "H"
            and item.first_element in policy.hydrogen_acceptor_elements
            and item.vdw_gap is not None
            and item.vdw_gap <= policy.hydrogen_acceptor_gap_angstrom
        )
    if not qualifying_evidence:
        return ()
    acceptor_site = sites[acceptor_id]
    accepted_acceptors = {
        component.element
        for component in acceptor_site.components
        if component.element in policy.hydrogen_acceptor_elements
    }
    if not accepted_acceptors:
        return ()

    candidates: list[HydrogenBondCandidate] = []
    context = contact_analysis._symmetry_context
    for bond in molecular_analysis.bond_orbits:
        if hydrogen_id not in (
            bond.first_independent_site_id,
            bond.second_independent_site_id,
        ):
            continue
        if hydrogen_id == bond.second_independent_site_id:
            donor_id = bond.first_independent_site_id
            donor_hydrogen_relation = bond.periodic_relation
        else:
            donor_id = bond.second_independent_site_id
            donor_hydrogen_relation = bond.periodic_relation.inverse(context)
        donor_site = sites[donor_id]
        accepted_donors = {
            component.element
            for component in donor_site.components
            if component.element in policy.hydrogen_donor_elements
        }
        accepted_pairs = tuple(sorted(
            (donor, acceptor)
            for donor in accepted_donors
            for acceptor in accepted_acceptors
        ))
        if not accepted_pairs:
            continue
        _, hydrogen_to_donor = _relation_vector(
            sites[hydrogen_id],
            donor_site,
            donor_hydrogen_relation.inverse(context),
            contact_analysis,
        )
        hydrogen_acceptor_distance, hydrogen_to_acceptor = _relation_vector(
            sites[hydrogen_id],
            acceptor_site,
            hydrogen_acceptor_relation,
            contact_analysis,
        )
        denominator = float(
            np.linalg.norm(hydrogen_to_donor) * np.linalg.norm(hydrogen_to_acceptor)
        )
        if denominator <= 0.0:
            continue
        cosine = float(
            np.dot(hydrogen_to_donor, hydrogen_to_acceptor) / denominator
        )
        angle = math.degrees(math.acos(max(-1.0, min(1.0, cosine))))
        if angle < policy.minimum_donor_hydrogen_acceptor_angle_deg:
            continue
        donor_acceptor_relation = donor_hydrogen_relation.compose(
            hydrogen_acceptor_relation,
            context,
        )
        donor_acceptor_distance, _ = _relation_vector(
            donor_site,
            acceptor_site,
            donor_acceptor_relation,
            contact_analysis,
        )
        interpretation_id = "hydrogen-bond-candidate:" + _digest({
            "intermolecular_contact_orbit_id": orbit.intermolecular_contact_orbit_id,
            "donor_hydrogen_bond_orbit_id": bond.bond_orbit_id,
            "donor_site_id": donor_id,
            "hydrogen_site_id": hydrogen_id,
            "acceptor_site_id": acceptor_id,
            "donor_hydrogen_relation": (
                donor_hydrogen_relation.operation_key,
                donor_hydrogen_relation.lattice_translation,
            ),
            "hydrogen_acceptor_relation": (
                hydrogen_acceptor_relation.operation_key,
                hydrogen_acceptor_relation.lattice_translation,
            ),
        })
        candidates.append(HydrogenBondCandidate(
            interpretation_id,
            donor_id,
            hydrogen_id,
            acceptor_id,
            bond.bond_orbit_id,
            hydrogen_acceptor_distance,
            donor_acceptor_distance,
            angle,
            donor_hydrogen_relation,
            hydrogen_acceptor_relation,
            accepted_pairs,
            ResolutionStatus.RESOLVED,
            (),
            (
                ("method", "cristma.hydrogen_bond_candidate:1"),
                ("criterion", "explicit_D-H...A_geometry"),
            ),
        ))
    return tuple(sorted(candidates, key=lambda item: item.interpretation_id))


@dataclass(frozen=True, slots=True)
class IntermolecularContactAnalyzer:
    """Resolve geometric contacts from one existing symmetry pair table."""

    policy: IntermolecularContactPolicy
    reference: ReferenceData | None = None

    def __post_init__(self) -> None:
        if not isinstance(self.policy, IntermolecularContactPolicy):
            raise TypeError("policy must be IntermolecularContactPolicy")
        if self.reference is not None and not isinstance(self.reference, ReferenceData):
            raise TypeError("reference must be ReferenceData or None")

    def analyze(
        self,
        contact_analysis: ContactAnalysisResult,
        molecular_analysis: MolecularAnalysisResult,
    ) -> IntermolecularContactAnalysisResult:
        if not isinstance(contact_analysis, ContactAnalysisResult):
            raise TypeError("contact_analysis must be ContactAnalysisResult")
        if not isinstance(molecular_analysis, MolecularAnalysisResult):
            raise TypeError("molecular_analysis must be MolecularAnalysisResult")
        reference = self.reference or ReferenceData.default()
        context = contact_analysis._symmetry_context
        geometry_by_id = {
            item.geometry_orbit_id: item
            for item in contact_analysis.pair_table.contact_orbits
        }
        if any(
            bond.geometry_orbit_id not in geometry_by_id
            for bond in molecular_analysis.bond_orbits
        ):
            raise ValueError("molecular analysis belongs to another pair table")
        discrete = molecular_analysis.molecule_orbits
        site_to_molecule: dict[str, MolecularComponentOrbit] = {}
        for molecule in discrete:
            for site_id in molecule.independent_site_ids:
                if site_id in site_to_molecule:
                    raise ValueError("a molecular site belongs to multiple molecule orbits")
                site_to_molecule[site_id] = molecule

        structure_sites = {site.id: site for site in contact_analysis._structure.sites}
        diagnostics: list[Diagnostic] = []
        has_explicit_hydrogen = any(
            component.element == "H"
            for molecule in discrete
            for site_id in molecule.independent_site_ids
            for component in structure_sites[site_id].components
        )
        if discrete and not has_explicit_hydrogen:
            diagnostics.append(Diagnostic(
                Severity.INFO,
                "crystal_chemistry.intermolecular.explicit_hydrogen_absent",
                "Hydrogen-bond candidates were not evaluated because no explicit H/D site is present",
            ))
        cutoff_incomplete = (
            contact_analysis.pair_table.cutoff + contact_analysis.pair_table.distance_tolerance
            < self.policy.maximum_distance_angstrom
        )
        if cutoff_incomplete:
            diagnostics.append(Diagnostic(
                Severity.WARNING,
                "crystal_chemistry.intermolecular.pair_cutoff_incomplete",
                "The existing symmetry pair table does not cover the requested intermolecular distance",
                recovery="recalculate contact analysis with a sufficient minimum_pair_cutoff",
            ))
        vdw_records = reference.vdw_radii.records
        vdw_dataset_id = vdw_records[0].dataset_id if vdw_records else "not_available"
        vdw_dataset_version = (
            vdw_records[0].dataset_version if vdw_records else "not_available"
        )
        output: list[IntermolecularContactOrbit] = []
        for geometry in contact_analysis.pair_table.contact_orbits:
            if geometry.representative_distance > (
                self.policy.maximum_distance_angstrom
                + contact_analysis.pair_table.distance_tolerance
            ):
                continue
            first_molecule = site_to_molecule.get(geometry.first_independent_site_id)
            second_molecule = site_to_molecule.get(geometry.second_independent_site_id)
            if first_molecule is None or second_molecule is None:
                continue
            molecule_relation = molecule_relation_for_atomic_pair(
                first_molecule,
                second_molecule,
                geometry.first_independent_site_id,
                geometry.second_independent_site_id,
                geometry.canonical_relation,
                context,
            )
            if _same_molecule_instance(
                first_molecule,
                second_molecule,
                molecule_relation,
                context,
            ):
                continue
            descriptor = canonical_molecule_contact_relation(
                first_molecule,
                second_molecule,
                molecule_relation,
                context,
            )
            evidence, evidence_diagnostics = _vdw_evidence(
                structure_sites[geometry.first_independent_site_id],
                structure_sites[geometry.second_independent_site_id],
                geometry.representative_distance,
                reference,
            )
            diagnostics.extend(evidence_diagnostics)
            complete = tuple(item for item in evidence if item.vdw_gap is not None)
            accepted = tuple(
                item
                for item in complete
                if item.vdw_gap <= self.policy.maximum_vdw_gap_angstrom  # type: ignore[operator]
            )
            missing = len(complete) != len(evidence) or not evidence
            if not accepted and not missing:
                continue
            status = (
                ResolutionStatus.INCOMPLETE
                if cutoff_incomplete
                or contact_analysis.pair_table.status is PairTableStatus.INCOMPLETE
                or molecular_analysis.status is ResolutionStatus.INCOMPLETE
                or missing
                else ResolutionStatus.AMBIGUOUS
                if len(accepted) != len(complete)
                or molecular_analysis.status is ResolutionStatus.AMBIGUOUS
                else ResolutionStatus.RESOLVED
            )
            vdw_values = tuple(item.vdw_gap for item in complete)
            normalized_values = tuple(item.normalized_distance for item in complete)
            contact_id = "intermolecular-contact-orbit:" + _digest({
                "symmetry_action": context.symmetry_action_fingerprint,
                "first_molecule_orbit_id": descriptor[0],
                "second_molecule_orbit_id": descriptor[1],
                "operation_key": descriptor[2].operation_key,
                "lattice_translation": descriptor[2].lattice_translation,
                "geometry_orbit_id": geometry.geometry_orbit_id,
            })
            contact_orbit = IntermolecularContactOrbit(
                contact_id,
                geometry.geometry_orbit_id,
                descriptor[0],
                descriptor[1],
                descriptor[2],
                geometry.first_independent_site_id,
                geometry.second_independent_site_id,
                geometry.representative_distance,
                evidence,
                (min(vdw_values), max(vdw_values)) if vdw_values else None,  # type: ignore[arg-type]
                (
                    min(normalized_values),
                    max(normalized_values),
                ) if normalized_values else None,  # type: ignore[arg-type]
                geometry.multiplicity_in_reference_cell,
                (),
                status,
                evidence_diagnostics,
                (
                    ("method", "cristma.intermolecular_contact_orbits:1"),
                    ("vdw_dataset_id", vdw_dataset_id),
                    ("vdw_dataset_version", vdw_dataset_version),
                ),
            )
            interpretations = _hydrogen_bond_candidates(
                contact_orbit,
                geometry,
                contact_analysis,
                molecular_analysis,
                self.policy,
            )
            output.append(replace(contact_orbit, interpretations=interpretations))

        ordered = tuple(sorted(output, key=lambda item: item.intermolecular_contact_orbit_id))
        statuses = tuple(item.status for item in ordered)
        status = (
            ResolutionStatus.NOT_APPLICABLE
            if not discrete
            else ResolutionStatus.INCOMPLETE
            if cutoff_incomplete
            or contact_analysis.pair_table.status is PairTableStatus.INCOMPLETE
            or molecular_analysis.status is ResolutionStatus.INCOMPLETE
            or ResolutionStatus.INCOMPLETE in statuses
            else ResolutionStatus.AMBIGUOUS
            if molecular_analysis.status is ResolutionStatus.AMBIGUOUS
            or ResolutionStatus.AMBIGUOUS in statuses
            else ResolutionStatus.RESOLVED
        )
        return IntermolecularContactAnalysisResult(
            contact_analysis,
            molecular_analysis,
            ordered,
            status,
            tuple(dict.fromkeys(diagnostics)),
            tuple(sorted(self.policy.get_config())),
            tuple(sorted((
                ("method", "cristma.intermolecular_contact_analysis:1"),
                ("pair_table_cutoff", contact_analysis.pair_table.cutoff),
                ("symmetry_context_fingerprint", context.fingerprint),
            ))),
        )


